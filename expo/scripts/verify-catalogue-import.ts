/**
 * Chapter 4 verification — supplier-document onboarding.
 *
 * Exercises the pure catalogue-import pipeline end to end (no network, no
 * database): CSV with varied headings and title rows, multi-sheet Excel
 * workbooks, text-based PDF price lists (standard + embedded fonts), and the
 * PDF limitations (scanned, encrypted, not a PDF). Checks the Roadmap's
 * flags — freight, zero prices, ambiguous price bases, supplier stock — and
 * duplicate / conflict protection on re-import. Execute with:
 *
 *   bun run expo/scripts/verify-catalogue-import.ts
 *
 * Exit code 0 = all assertions pass. PDF fixtures are generated by
 * scripts/fixtures/make-pdf-fixtures.ts.
 */
