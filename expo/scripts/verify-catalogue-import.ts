let failures = 0;
let passes = 0;
function check(label: string, actual: unknown, expected: unknown): void {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a === e) {
    passes++;
    console.log(`  PASS  ${label}`);
  } else {
    failures++;
    console.error(`  FAIL  ${label}\n        expected ${e}\n        actual   ${a}`);
  }
}
const section = (t: string) => console.log(`\n${t}`);
const FIXTURES = join(process.cwd(), process.cwd().endsWith('expo') ? '' : 'expo', 'scripts', 'fixtures');
const fixture = (f: string) => new Uint8Array(readFileSync(join(FIXTURES, f)));
const enc = (s: string) => new TextEncoder().encode(s);
const mapOf = (headers: string[], m: ColumnMapping) =>
  Object.fromEntries(headers.map((h, i) => [h, m[i]]).filter(([, f]) => f));
const issueCodes = (d: CatalogueDraft) => d.issues.map(i => i.code);
const FS = { name: 'Fastener Supplies', email: 'orders@fastenersupplies.com', id: 'sup-1' };

async function run() {
  // -------------------------------------------------------------------------
  section('Value parsing');
  check('price with $ and ex GST', parseMoney('$12.50 ex GST').value, 12.5);
  check('price with thousands separator', parseMoney('1,234.50').value, 1234.5);
  check('zero price flagged, not a value', parseMoney('0.00'), { issue: 'zero' });
  check('POA flagged', parseMoney('POA').issue, 'poa');
  check('basis "per 100"', parsePriceBasis('per 100'), { quantity: 100, unit: 'each' });
  check('basis "/1000"', parsePriceBasis('/1000'), { quantity: 1000, unit: 'each' });
  check('basis "EA"', parsePriceBasis('EA'), { quantity: 1, unit: 'each' });
  check('basis "LM" → per metre', parsePriceBasis('LM'), { quantity: 1, unit: 'metre' });
  check('basis "C" interpreted (needs confirm)', parsePriceBasis('C').interpreted !== undefined, true);
  check('basis "M" ambiguous (thousand or metre)', parsePriceBasis('M').ambiguous !== undefined, true);
  check('basis nonsense ambiguous', parsePriceBasis('see note').ambiguous !== undefined, true);
  check('pack "Box of 1,000"', parsePackQuantity('Box of 1,000'), { quantity: 1000 });
  check('pack "CTN 12"', parsePackQuantity('CTN 12'), { quantity: 12 });
  check('pack "100/box"', parsePackQuantity('100/box'), { quantity: 100 });
  check('pack "12 x 300ml"', parsePackQuantity('12 x 300ml'), { quantity: 12 });
  check('pack "300ml cartridge" is unclear, not 300', parsePackQuantity('300ml cartridge'), { unclear: true });
  check('pack "EA" = 1', parsePackQuantity('EA'), { quantity: 1 });
  check('base64 decode', bytesToText(base64ToBytes('U21hcnRTdG9jayDinJM=')), 'SmartStock ✓');
  check('source detection', [detectSource('a.CSV'), detectSource('b.xlsx'), detectSource('c.pdf'), detectSource('d.doc')], ['csv', 'xlsx', 'pdf', null]);

  // -------------------------------------------------------------------------
  section('CSV with title rows and supplier-specific headings');
  const csv = [
    'Acme Fasteners — Trade Price List',
    'Effective 1 October 2026,,,,,',
    'Part No.,Item Description,Pack Size,Nett Price (ex GST),Price Per,SOH',
    'AF-100,"Bugle Screw 6g x 25mm, Black",Box of 1000,9.80,per 100,"12,000"',
    'AF-101,Bugle Screw 8g x 40mm,Box of 500,0.00,per 100,500',
    'AF-102,Hex Bolt M10 x 100,Box of 50,32.00,M,40',
    'AF-103,Coach Screw 10 x 75,Box of 100,28.00,,10',
    'FRT,Freight Charge,,15.00,,',
    ',,,,,',
    'AF-104,,Box of 10,5.00,EA,1',
    'AF-100,"Bugle Screw 6g x 25mm, Black",Box of 1000,9.80,per 100,"12,000"',
  ].join('\r\n');
  const parsedCsv = await parseCatalogueFile(enc(csv), 'acme.csv', 'csv');
  const sheet = parsedCsv.sheets[0];
  const hdr = detectHeaderRow(sheet.rows);
  check('header row detected below title rows', hdr, 2);
  const table = sheetToTable(sheet, hdr);
  const mapping = autoMapColumns(table.headers, table.rows.slice(0, 20).map(r => r.cells));
  check('auto-mapping of supplier headings', mapOf(table.headers, mapping), {
    'Part No.': 'supplierCode',
    'Item Description': 'name',
    'Pack Size': 'orderUnit',
    'Nett Price (ex GST)': 'purchasePrice',
    'Price Per': 'priceBasisQuantity',
  });
  check('supplier stock column (SOH) never auto-mapped, but flagged', supplierStockColumns(table.headers, mapping), ['SOH']);
  check('blank rows skipped, row numbers preserved', table.rows.map(r => r.rowNumber), [4, 5, 6, 7, 8, 10, 11]);

  const drafts = buildDrafts(table, mapping, { source: 'csv', supplier: FS }, sheet);
  const [screw, zero, mBasis, noBasis, freight, noName, repeat] = drafts;
  check('quoted comma kept in name', screw.product.name, 'Bugle Screw 6g x 25mm, Black');
  check('screw ready to import', screw.status, 'ready');
  check('screw pack qty from "Box of 1000"', screw.product.unitsPerOrderUnit, 1000);
  check('screw priced per 100', [screw.product.purchasePrice, screw.product.priceBasisQuantity, screw.product.priceBasisUnit], [9.8, 100, 'each']);
  check('screw linked to selected supplier record', [screw.product.supplier, screw.product.supplierEmail, screw.product.supplierId], ['Fastener Supplies', 'orders@fastenersupplies.com', 'sup-1']);
  check('legacy cost derived per stock unit (9.80/100)', screw.product.cost, 0.098);
  check('legacy sku = supplier code', screw.product.sku, 'AF-100');
  check('barcode left empty until insert', screw.product.barcode, '');
  check('supplier stock never imported as own stock', screw.product.currentStock, 0);
  check('order line total uses price basis (1 box = 1000 → $98)', lineTotalExGst(screw.product, 1), 98);
  check('zero price → review, price left blank', [zero.status, zero.product.purchasePrice, issueCodes(zero).includes('zero-price')], ['review', undefined, true]);
  check('"M" basis → review, basis not guessed', [mBasis.status, mBasis.product.priceBasisQuantity, issueCodes(mBasis).includes('ambiguous-basis')], ['review', undefined, true]);
  check('price + pack with no basis → ambiguous, flagged', [noBasis.status, issueCodes(noBasis).includes('ambiguous-basis')], ['review', true]);
  check('freight line flagged and excluded by default', [freight.status, issueCodes(freight).includes('freight'), freight.includeByDefault], ['review', true, false]);
  check('missing name → invalid', [noName.status, noName.includeByDefault], ['invalid', false]);
  check('only clean rows selected by default', drafts.filter(d => d.includeByDefault).map(d => d.rowNumber), [4, 11]);

  const reviewed = reviewDrafts([], drafts);
  check('in-file repeat detected as duplicate', reviewed[6].category, 'existing');
  check('in-file repeat not importable', reviewed[6].importable, false);
  const sum = summariseReview(reviewed);
  check('review summary', [sum.ready, sum.duplicatesInFile, sum.review, sum.invalid], [1, 1, 4, 1]);

  // Editing a row re-validates it.
  const fixed = buildDraft(mBasis.key, mBasis.rowNumber, { ...mBasis.values, priceBasisQuantity: '1000' }, { source: 'csv', supplier: FS });
  check('editing the basis resolves the review flag', [fixed.status, fixed.product.priceBasisQuantity], ['ready', 1000]);

  // -------------------------------------------------------------------------
  section('Re-import, duplicates and conflicts against the existing catalogue');
  const existing: Product[] = [
    { ...screw.product, id: 'p1', barcode: '9300000000017' },
    { ...noBasis.product, id: 'p2', barcode: '9300000000024', purchasePrice: 26.0 },
  ];
  const second = reviewDrafts(existing, drafts);
  check('same supplier code + same data → existing (no duplicate created)', [second[0].category, second[0].match.match?.id], ['existing', 'p1']);
  check('same code but changed price → conflict, existing left unchanged', second[3].category, 'conflict');
  check('conflict reason explains the difference', /purchase price/.test(second[3].match.reason), true);
  check('conflicts never importable', second[3].importable, false);
  check('existing catalogue untouched', existing[1].purchasePrice, 26);
  const otherSupplier = buildDraft('x', 1, { supplierCode: 'AF-100', name: 'Different product' }, { source: 'csv', supplier: { name: 'Other Supplier' } });
  check('same code from a DIFFERENT supplier is not a match', reviewDrafts(existing, [otherSupplier])[0].category, 'review' === otherSupplier.status ? 'review' : 'ready');
  const byBarcode = buildDraft('y', 1, { barcode: '9300000000017', name: 'Bugle Screw 6g x 25mm, Black', supplierCode: 'AF-100' }, { source: 'csv', supplier: FS });
  check('barcode match wins', reviewDrafts(existing, [byBarcode])[0].match.match?.id, 'p1');

  // -------------------------------------------------------------------------
  section('Excel workbook with several worksheets');
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([['Seal Supply Co'], ['Terms: 30 days']]), 'Cover');
  XLSX.utils.book_append_sheet(
    wb,
    XLSX.utils.aoa_to_sheet([
      ['Seal Supply Co price file'],
      [],
      ['Code', 'Product', 'Barcode', 'Carton Qty', 'Unit Price', 'Category', 'Available'],
      ['SS-C300', 'Silicone Clear 300ml', '9312345000011', 12, 4.2, 'Sealants', 340],
      ['SS-W300', 'Silicone White 300ml', '9312345000028', 12, 4.35, 'Sealants', 0],
      ['SS-GUN', 'Caulking Gun Heavy Duty', '9312345000035', 1, 18.5, 'Tools', 25],
    ]),
    'Prices',
  );
  const xbytes = new Uint8Array(XLSX.write(wb, { type: 'array', bookType: 'xlsx' }) as ArrayBuffer);
  const xfile = await parseCatalogueFile(xbytes, 'seal.xlsx', 'xlsx');
  check('all worksheets listed', xfile.sheets.map(s => s.name), ['Cover', 'Prices']);
  const xs = xfile.sheets[1];
  const xh = detectHeaderRow(xs.rows);
  check('header row found on second sheet', xh, 1);
  const xt = sheetToTable(xs, xh);
  const xm = autoMapColumns(xt.headers, xt.rows.map(r => r.cells));
  check('xlsx mapping', mapOf(xt.headers, xm), {
    Code: 'supplierCode', Product: 'name', Barcode: 'barcode', 'Carton Qty': 'unitsPerOrderUnit', 'Unit Price': 'purchasePrice', Category: 'category',
  });
  check('"Available" flagged as supplier stock', supplierStockColumns(xt.headers, xm), ['Available']);
  const xd = buildDrafts(xt, xm, { source: 'xlsx', supplier: { name: 'Seal Supply Co' } }, xs);
  check('numeric cells read as text values', xd[0].product.purchasePrice, 4.2);
  check('order unit derived from carton qty (flagged as info)', [xd[0].product.orderUnit, issueCodes(xd[0]).includes('derived-order-unit')], ['pack of 12', true]);
  check('per-item vs per-carton price asks for confirmation', xd[0].status, 'review');
  check('pack of 1 needs no basis confirmation', xd[2].status, 'ready');
  const xd0Confirmed = buildDraft(xd[0].key, xd[0].rowNumber, { ...xd[0].values, priceBasisQuantity: '1' }, { source: 'xlsx', supplier: { name: 'Seal Supply Co' } });
  check('confirming "per item" makes the row ready', xd0Confirmed.status, 'ready');

  // -------------------------------------------------------------------------
  section('Structured CSV template still works through the new flow (fallback kept)');
  const tSheet = parseCsvToSheet(generateCSVTemplate());
  const tTable = sheetToTable(tSheet, detectHeaderRow(tSheet.rows));
  const tMap = autoMapColumns(tTable.headers, tTable.rows.map(r => r.cells));
  const tMapped = mapOf(tTable.headers, tMap) as Record<string, TargetField>;
  check('template purchasing columns mapped', [tMapped.supplier_code, tMapped.order_unit, tMapped.units_per_order_unit, tMapped.purchase_price, tMapped.price_basis_quantity, tMapped.price_basis_unit, tMapped.stock_unit], ['supplierCode', 'orderUnit', 'unitsPerOrderUnit', 'purchasePrice', 'priceBasisQuantity', 'priceBasisUnit', 'stockUnit']);
  check('template own-stock column mapped (explicit current_stock only)', tMapped.current_stock, 'currentStock');
  const tDrafts = buildDrafts(tTable, tMap, { source: 'csv', supplier: {} }, tSheet);
  check('template rows ready', tDrafts.map(d => d.status), ['ready', 'ready']);
  check('template supplier from file column when no record chosen', tDrafts[0].product.supplier, 'Fastener Supplies');
  check('legacy batch matcher still works', matchProductsForImport([], tDrafts.map(d => d.product)).toAdd.length, 2);

  // -------------------------------------------------------------------------
  section('PDF price list — standard fonts, two pages');
  const pdf = await parseCatalogueFile(fixture('price-list-standard.pdf'), 'fs.pdf', 'pdf');
  const ps = pdf.sheets[0];
  check('header + 7 product rows (titles, totals, footers, repeated header removed)', ps.rows.length, 8);
  const pt = sheetToTable(ps, detectHeaderRow(ps.rows));
  const pm = autoMapColumns(pt.headers, pt.rows.map(r => r.cells));
  check('pdf mapping', mapOf(pt.headers, pm), { 'Item Code': 'supplierCode', Description: 'name', Pack: 'orderUnit', Price: 'purchasePrice', Per: 'priceBasisQuantity' });
  check('pdf "Available" flagged as supplier stock', supplierStockColumns(pt.headers, pm), ['Available']);
  const pd = buildDrafts(pt, pm, { source: 'pdf', supplier: FS }, ps);
  check('right-aligned prices land in the price column', pd.map(d => d.product.purchasePrice), [12.5, 18.9, undefined, 45, 4.2, 25, 6.8]);
  check('pdf rows carry a verify note', issueCodes(pd[0]).includes('pdf-source'), true);
  check('pdf statuses (zero price, M basis, freight flagged)', pd.map(d => d.status), ['ready', 'ready', 'review', 'review', 'ready', 'review', 'ready']);
  check('pdf freight excluded by default', pd[5].includeByDefault, false);
  check('timber priced per lineal metre', [pd[6].product.priceBasisQuantity, pd[6].product.priceBasisUnit], [1, 'metre']);
  check('notes explain what was left out', pdf.notes.some(n => /not product rows/.test(n)), true);

  section('PDF price list — embedded TrueType font (ToUnicode)');
  const pdf2 = await parseCatalogueFile(fixture('price-list-embedded.pdf'), 'pk.pdf', 'pdf');
  const p2t = sheetToTable(pdf2.sheets[0], detectHeaderRow(pdf2.sheets[0].rows));
  const p2m = autoMapColumns(p2t.headers, p2t.rows.map(r => r.cells));
  const p2d = buildDrafts(p2t, p2m, { source: 'pdf', supplier: FS }, pdf2.sheets[0]);
  check('unicode text decoded exactly', p2d.map(d => d.product.name), ['Packing Strap 12mm × 1000m – Black', 'Shipping Carton 450×350×300', 'Tape Ø48mm Clear']);
  check('embedded pdf prices', p2d.map(d => d.product.purchasePrice), [38.5, 61.25, 72]);
  check('"Bundle of 25" pack', p2d[1].product.unitsPerOrderUnit, 25);

  section('PDF limitations are explained, never guessed');
  const limitation = async (bytes: Uint8Array) => {
    try { await parseCatalogueFile(bytes, 'x.pdf', 'pdf'); return 'parsed'; }
    catch (e) { return e instanceof PdfLimitationError ? e.kind : 'other-error'; }
  };
  check('scanned (image-only) PDF → no-text limitation', await limitation(fixture('scanned.pdf')), 'no-text');
  check('encrypted PDF → encrypted limitation', await limitation(enc('%PDF-1.4\n1 0 obj << /Type /Catalog >> endobj\ntrailer << /Root 1 0 R /Encrypt 2 0 R >>\n%%EOF')), 'encrypted');
  check('not a PDF → unreadable', await limitation(enc('hello world')), 'unreadable');
  check('PDF text without a product table → unreadable (explained)', await limitation(handmadePdf(['BT /F1 12 Tf 72 700 Td (Dear customer, thanks for your order.) Tj ET'])), 'unreadable');

  section('Handmade PDF — TJ kerning, T*, compressed stream');
  const hm = handmadePdf([
    'BT /F1 10 Tf 14 TL 40 700 Td [(Code)] TJ 100 0 Td (Name) Tj 200 0 Td (Price) Tj ET',
    'BT /F1 10 Tf 40 686 Td [(A-) -20 (1)] TJ 100 0 Td [(Hinge ) 10 (Brass)] TJ 200 0 Td (3.10) Tj ET',
    'BT /F1 10 Tf 40 672 Td (A-2) Tj 100 0 Td (Hinge Steel) Tj 200 0 Td (2.95) Tj ET',
  ], true);
  const hmf = await parseCatalogueFile(hm, 'h.pdf', 'pdf');
  check('kerned runs reassembled into cells', hmf.sheets[0].rows, [['Code', 'Name', 'Price'], ['A-1', 'Hinge Brass', '3.10'], ['A-2', 'Hinge Steel', '2.95']]);

  console.log(`\n${passes} passed, ${failures} failed`);
  if (failures > 0) {
    console.error('Catalogue import checks FAILED.');
    process.exit(1);
  }
  console.log('All catalogue import checks passed.');
}

/** Minimal single-page PDF writer (Helvetica) for parser edge cases. */
function handmadePdf(contentLines: string[], compress = false): Uint8Array {
  const content = contentLines.join('\n');
  const streamBytes = compress ? zlibSync(enc(content)) : enc(content);
  const objs: (string | Uint8Array)[][] = [
    ['<< /Type /Catalog /Pages 2 0 R >>'],
    ['<< /Type /Pages /Kids [3 0 R] /Count 1 >>'],
    ['<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>'],
    [`<< /Length ${streamBytes.length}${compress ? ' /Filter /FlateDecode' : ''} >>\nstream\n`, streamBytes, '\nendstream'],
    ['<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>'],
  ];
  const parts: Uint8Array[] = [enc('%PDF-1.4\n')];
  objs.forEach((o, i) => {
    parts.push(enc(`${i + 1} 0 obj\n`));
    o.forEach(p => parts.push(typeof p === 'string' ? enc(p) : p));
    parts.push(enc('\nendobj\n'));
  });
  parts.push(enc('trailer\n<< /Root 1 0 R /Size 6 >>\n%%EOF\n'));
  const total = parts.reduce((n, p) => n + p.length, 0);
  const out = new Uint8Array(total);
  let off = 0;
  parts.forEach(p => { out.set(p, off); off += p.length; });
  return out;
}

run().catch(err => {
  console.error(err);
  process.exit(1);
});
