import assert from 'node:assert/strict';
import { scopedStocktakeJournal, scopedStocktakeKey } from '../utils/scopedStocktakeJournal';
const u='11111111-1111-4111-8111-111111111111', a='aaaaaaaa-0000-4000-8000-000000000001', b='bbbbbbbb-0000-4000-8000-000000000002';
const data=new Map<string,string>();
const storage={ getItem:async(k:string)=>data.get(k)??null, setItem:async(k:string,v:string)=>{data.set(k,v);}, removeItem:async(k:string)=>{data.delete(k);} };
const first=scopedStocktakeJournal({userId:u,businessId:a},storage), second=scopedStocktakeJournal({userId:u,businessId:b},storage);
const attempt={id:'22222222-2222-4222-8222-222222222222',items:[{productId:'33333333-3333-4333-8333-333333333333',name:'Synthetic',barcode:'01',expectedQuantity:2,actualQuantity:0,discrepancy:-2}]};
await first.write(attempt);
assert.deepEqual(await first.read(),attempt);
assert.equal(await second.read(),null,'A business switch must not replay another business count');
assert.deepEqual(await scopedStocktakeJournal({userId:u,businessId:a},storage).read(),attempt,'Restart preserves request identity');
await assert.rejects(first.write({...attempt,id:'44444444-4444-4444-8444-444444444444'}),/existing stocktake/);
await assert.rejects(first.write({...attempt,items:[{...attempt.items[0],actualQuantity:1}]}),/existing stocktake/);
await assert.rejects(first.clear('wrong'),/must not be cleared/);
assert.ok(data.has(first.key));
data.set(second.key,data.get(first.key)!);
await assert.rejects(second.read(),/different account or business/);
assert.ok(data.has(second.key),'Corrupt or foreign data must not be silently deleted');
data.delete(second.key);
data.set('stocktake-save-v1:'+u,JSON.stringify(attempt));
await assert.rejects(second.write(attempt),/older unfinished/);
assert.ok(data.has('stocktake-save-v1:'+u));
data.delete('stocktake-save-v1:'+u);
await second.write(attempt);
await first.clear(attempt.id);
assert.equal(await first.read(),null);
assert.deepEqual(await second.read(),attempt,'Clearing business A cannot clear B');
assert.equal(scopedStocktakeKey({userId:u,businessId:a.toUpperCase()}),first.key);
assert.throws(()=>scopedStocktakeKey({userId:'invalid',businessId:a}),/identity/);
await assert.rejects(second.write({...attempt,id:'invalid'}),/invalid/);
const broken=scopedStocktakeJournal({userId:u,businessId:a},{...storage,setItem:async()=>{throw new Error('storage full');}});
await assert.rejects(broken.write(attempt),/storage full/);
assert.equal(await first.read(),null);
console.log('PASS scoped stocktake journal: business isolation, restart identity, legacy preservation, corrupted scope, wrong-clear protection and storage failure');
